// Gateway A1 content banks used by the activity generator.
//
// Vocabulary entries are written "english|español". Alternatives accepted when the
// student types the answer are separated by "/" (the first one is the one shown).
// Grammar items are gap-fill sentences. Any hint needed to make the gap unambiguous
// (base verb, Spanish meaning, negative form) goes in brackets inside the sentence,
// so the same item works as multiple choice and as a written answer.

export interface GrammarItem {
  sentence: string;
  answer: string;
  distractors: string[];
  /** 1 = básico, 2 = intermedio, 3 = reto. */
  level: 1 | 2 | 3;
  /** Items without a gap (e.g. "Elige la frase correcta") can only be multiple choice. */
  choiceOnly?: boolean;
}

export function g(sentence: string, answer: string, distractors: string[], level: 1 | 2 | 3 = 1): GrammarItem {
  return { sentence, answer, distractors, level };
}

export function pick(sentence: string, answer: string, distractors: string[], level: 1 | 2 | 3 = 2): GrammarItem {
  return { sentence, answer, distractors, level, choiceOnly: true };
}

